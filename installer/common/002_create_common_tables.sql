-- 1. Table de Contrôle de l'Installation
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count 
    FROM DBA_TABLES 
    WHERE OWNER = 'C##ZIRIOAM_ADMIN' AND TABLE_NAME = 'ZIRIOAM_INSTALLATION';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE C##ZIRIOAM_ADMIN.ZIRIOAM_INSTALLATION
        (
            INSTALLATION_ID    NUMBER GENERATED ALWAYS AS IDENTITY,
            PRODUCT_CODE       VARCHAR2(30) NOT NULL,
            PRODUCT_VERSION    VARCHAR2(30) NOT NULL,
            INSTALL_DATE       TIMESTAMP DEFAULT SYSTIMESTAMP,
            INSTALL_STATUS     VARCHAR2(20) NOT NULL,
            CONTAINER_NAME     VARCHAR2(128) NOT NULL,
            ORACLE_VERSION     VARCHAR2(256),
            CHECKSUM_MANIFEST  VARCHAR2(64),
            CONSTRAINT PK_ZIRIOAM_CDB_INSTALL PRIMARY KEY (INSTALLATION_ID),
            CONSTRAINT UK_ZIRIOAM_CDB_PROD UNIQUE (PRODUCT_CODE)
        )';
    END IF;
END;
/

-- 2. Journal Détaillé d'Installation (Suivi des étapes et reprise sur incident)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count 
    FROM DBA_TABLES 
    WHERE OWNER = 'C##ZIRIOAM_ADMIN' AND TABLE_NAME = 'ZIRIOAM_INSTALL_LOG';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE C##ZIRIOAM_ADMIN.ZIRIOAM_INSTALL_LOG
        (
            LOG_ID           NUMBER GENERATED ALWAYS AS IDENTITY,
            STEP_NUMBER      NUMBER NOT NULL,
            STEP_NAME        VARCHAR2(100) NOT NULL,
            OBJECT_TYPE      VARCHAR2(30),
            OBJECT_NAME      VARCHAR2(128),
            STATUS           VARCHAR2(20) NOT NULL, -- PENDING, RUNNING, SUCCESS, FAILED
            ERROR_CODE       NUMBER,
            ERROR_MESSAGE    VARCHAR2(4000),
            EXECUTED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP,
            CONSTRAINT PK_ZIRIOAM_CDB_INSTLOG PRIMARY KEY (LOG_ID)
        )';
    END IF;
END;
/

-- 3. Référentiel des Identités Développeurs au niveau CDB
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count 
    FROM DBA_TABLES 
    WHERE OWNER = 'C##ZIRIOAM_ADMIN' AND TABLE_NAME = 'ZIRIOAM_DEVELOPERS';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE C##ZIRIOAM_ADMIN.ZIRIOAM_DEVELOPERS
        (
            DEVELOPER_ID   NUMBER GENERATED ALWAYS AS IDENTITY,
            USERNAME       VARCHAR2(128) NOT NULL, -- Identifiant normalisé sans C## (ex: ALI, A1)
            ORACLE_USER    VARCHAR2(128) NOT NULL, -- Identifiant Oracle complet (ex: C##ALI, C##A1)
            FULL_NAME      VARCHAR2(255) NOT NULL,
            EMAIL          VARCHAR2(255) NOT NULL,
            STATUS         VARCHAR2(20) DEFAULT ''ACTIVE'' NOT NULL, -- ACTIVE, INACTIVE, SUSPENDED
            CREATED_BY     VARCHAR2(128) DEFAULT USER,
            CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_ZIRIOAM_DEVELOPERS PRIMARY KEY (DEVELOPER_ID),
            CONSTRAINT UK_ZIRIOAM_DEV_USER UNIQUE (USERNAME),
            CONSTRAINT UK_ZIRIOAM_DEV_ORA UNIQUE (ORACLE_USER),
            CONSTRAINT CHK_ZIRIOAM_DEV_STATUS CHECK (STATUS IN (''ACTIVE'', ''INACTIVE'', ''SUSPENDED''))
        )';
        
        EXECUTE IMMEDIATE 'CREATE INDEX C##ZIRIOAM_ADMIN.IDX_ZIRIOAM_DEV_MAIL ON C##ZIRIOAM_ADMIN.ZIRIOAM_DEVELOPERS(EMAIL)';
    END IF;
END;
/

