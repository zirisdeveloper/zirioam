CREATE OR REPLACE VIEW ZIRIOAM_OWNER.V_ZIRIOAM_ACCESS_MATRIX AS
SELECT 
    da.ACCESS_ID,
    da.USERNAME,
    da.TARGET_SCHEMA,
    ar.ROLE_NAME,
    ar.PROFILE_TYPE,
    da.CAN_DDL_CREATE,
    da.CAN_DDL_ALTER,
    da.CAN_DDL_DROP,
    da.STATUS,
    da.GRANTED_BY,
    da.GRANTED_AT,
    da.UPDATED_AT
FROM ZIRIOAM_OWNER.ZIRIOAM_DEVELOPER_ACCESS da
LEFT JOIN ZIRIOAM_OWNER.ZIRIOAM_ACCESS_ROLES ar ON da.ROLE_ID = ar.ROLE_ID;

CREATE OR REPLACE VIEW ZIRIOAM_OWNER.V_ZIRIOAM_PDB_METRICS AS
SELECT 
    (SELECT COUNT(DISTINCT USERNAME) FROM ZIRIOAM_OWNER.ZIRIOAM_DEVELOPER_ACCESS WHERE STATUS = 'ACTIVE') AS ACTIVE_DEVELOPERS,
    (SELECT COUNT(*) FROM ZIRIOAM_OWNER.ZIRIOAM_ACCESS_ROLES WHERE IS_ACTIVE = 'Y') AS ACTIVE_ROLES,
    (SELECT COUNT(*) FROM ZIRIOAM_OWNER.ZIRIOAM_DEVELOPER_ACCESS WHERE CAN_DDL_CREATE = 1 OR CAN_DDL_ALTER = 1 OR CAN_DDL_DROP = 1) AS DDL_AUTHORIZED_USERS,
    (SELECT COUNT(*) FROM ZIRIOAM_OWNER.ZIRIOAM_EXECUTION_HISTORY WHERE EXECUTION_STATUS = 'SUCCESS') AS SUCCESSFUL_DDL_COUNT,
    (SELECT COUNT(*) FROM ZIRIOAM_OWNER.ZIRIOAM_EXECUTION_HISTORY WHERE EXECUTION_STATUS = 'FAILED') AS FAILED_DDL_COUNT
FROM DUAL;

