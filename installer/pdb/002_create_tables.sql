-- 3. Rôles Fonctionnels Applicatifs Gérés par ZIRIOAM dans la PDB
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'ZIRIOAM_OWNER' AND TABLE_NAME = 'ZIRIOAM_ACCESS_ROLES';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE ZIRIOAM_OWNER.ZIRIOAM_ACCESS_ROLES
        (
            ROLE_ID          NUMBER GENERATED ALWAYS AS IDENTITY,
            ROLE_NAME        VARCHAR2(128) NOT NULL, -- Ex: R_GESTION_READ, R_GESTION_WRITE
            TARGET_SCHEMA    VARCHAR2(128) NOT NULL, -- Ex: GESTION
            PROFILE_TYPE     VARCHAR2(30) NOT NULL,  -- APP_READ, APP_WRITE, APP_READ_WRITE, APP_EXECUTE
            DESCRIPTION      VARCHAR2(500),
            IS_ACTIVE        CHAR(1) DEFAULT ''Y'' NOT NULL,
            CREATED_BY       VARCHAR2(128) DEFAULT USER,
            CREATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_ZIRIOAM_ROLES PRIMARY KEY (ROLE_ID),
            CONSTRAINT UK_ZIRIOAM_ROLE_NAME UNIQUE (ROLE_NAME),
            CONSTRAINT CHK_ZIRIOAM_ROLE_ACTIVE CHECK (IS_ACTIVE IN (''Y'', ''N''))
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX ZIRIOAM_OWNER.IDX_ZIRIOAM_ROLE_SCH ON ZIRIOAM_OWNER.ZIRIOAM_ACCESS_ROLES(TARGET_SCHEMA)';
    END IF;
END;
/

-- 4. Privilèges Accordés aux Rôles (Matrice DML Granulaire)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'ZIRIOAM_OWNER' AND TABLE_NAME = 'ZIRIOAM_ROLE_PRIVILEGES';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE ZIRIOAM_OWNER.ZIRIOAM_ROLE_PRIVILEGES
        (
            PRIV_ID          NUMBER GENERATED ALWAYS AS IDENTITY,
            ROLE_ID          NUMBER NOT NULL,
            PRIVILEGE_TYPE   VARCHAR2(30) NOT NULL, -- SELECT, INSERT, UPDATE, DELETE, EXECUTE
            OBJECT_TYPE      VARCHAR2(30) NOT NULL, -- TABLE, VIEW, SEQUENCE, PACKAGE, PROCEDURE, FUNCTION
            OBJECT_NAME      VARCHAR2(128) NOT NULL,
            GRANTED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_ZIRIOAM_PRIVS PRIMARY KEY (PRIV_ID),
            CONSTRAINT FK_ZIRIOAM_PRIV_ROLE FOREIGN KEY (ROLE_ID) 
                REFERENCES ZIRIOAM_OWNER.ZIRIOAM_ACCESS_ROLES(ROLE_ID) ON DELETE CASCADE,
            CONSTRAINT UK_ZIRIOAM_ROLE_PRIV UNIQUE (ROLE_ID, PRIVILEGE_TYPE, OBJECT_TYPE, OBJECT_NAME)
        )';
    END IF;
END;
/

-- 5. Matrice d'Accès des Développeurs aux Schémas (Séparation Stricte DDL / DML)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'ZIRIOAM_OWNER' AND TABLE_NAME = 'ZIRIOAM_DEVELOPER_ACCESS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE ZIRIOAM_OWNER.ZIRIOAM_DEVELOPER_ACCESS
        (
            ACCESS_ID        NUMBER GENERATED ALWAYS AS IDENTITY,
            USERNAME         VARCHAR2(128) NOT NULL, -- Identifiant Oracle du développeur (ex: C##ALI)
            TARGET_SCHEMA    VARCHAR2(128) NOT NULL, -- Schéma cible (ex: GESTION)
            ROLE_ID          NUMBER,                 -- Rôle DML assigné (peut être NULL si DDL uniquement)
            CAN_DDL_CREATE   NUMBER(1) DEFAULT 0 NOT NULL, -- DDL CREATE TABLE, VIEW, etc.
            CAN_DDL_ALTER    NUMBER(1) DEFAULT 0 NOT NULL, -- DDL ALTER TABLE, etc.
            CAN_DDL_DROP     NUMBER(1) DEFAULT 0 NOT NULL, -- DDL DROP TABLE, etc.
            STATUS           VARCHAR2(20) DEFAULT ''ACTIVE'' NOT NULL, -- ACTIVE, REVOKED
            GRANTED_BY       VARCHAR2(128) NOT NULL,
            GRANTED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            UPDATED_AT       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_ZIRIOAM_DEV_ACCESS PRIMARY KEY (ACCESS_ID),
            CONSTRAINT FK_ZIRIOAM_ACC_ROLE FOREIGN KEY (ROLE_ID) 
                REFERENCES ZIRIOAM_OWNER.ZIRIOAM_ACCESS_ROLES(ROLE_ID) ON DELETE SET NULL,
            CONSTRAINT UK_ZIRIOAM_USER_SCH UNIQUE (USERNAME, TARGET_SCHEMA),
            CONSTRAINT CHK_ZIRIOAM_ACC_STAT CHECK (STATUS IN (''ACTIVE'', ''REVOKED'')),
            CONSTRAINT CHK_ZIRIOAM_CAN_CREATE CHECK (CAN_DDL_CREATE IN (0, 1)),
            CONSTRAINT CHK_ZIRIOAM_CAN_ALTER CHECK (CAN_DDL_ALTER IN (0, 1)),
            CONSTRAINT CHK_ZIRIOAM_CAN_DROP CHECK (CAN_DDL_DROP IN (0, 1))
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX ZIRIOAM_OWNER.IDX_ZIRIOAM_ACC_USER ON ZIRIOAM_OWNER.ZIRIOAM_DEVELOPER_ACCESS(USERNAME)';
    END IF;
END;
/

-- 6. Historique d'Exécution du Moteur DDL Contrôlé
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'ZIRIOAM_OWNER' AND TABLE_NAME = 'ZIRIOAM_EXECUTION_HISTORY';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE ZIRIOAM_OWNER.ZIRIOAM_EXECUTION_HISTORY
        (
            EXECUTION_ID         NUMBER GENERATED ALWAYS AS IDENTITY,
            USERNAME             VARCHAR2(128) NOT NULL,
            TARGET_SCHEMA        VARCHAR2(128) NOT NULL,
            DDL_OPERATION        VARCHAR2(30) NOT NULL, -- CREATE, ALTER, DROP
            OBJECT_TYPE          VARCHAR2(30) NOT NULL, -- TABLE, VIEW, INDEX, SEQUENCE, PROCEDURE, FUNCTION, PACKAGE
            OBJECT_NAME          VARCHAR2(128) NOT NULL,
            DDL_STATEMENT        CLOB,
            EXECUTION_STATUS     VARCHAR2(20) NOT NULL, -- SUCCESS, REJECTED, FAILED
            ORACLE_ERROR_CODE    NUMBER,
            ORACLE_ERROR_MESSAGE VARCHAR2(4000),
            EXECUTED_AT          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT PK_ZIRIOAM_EXEC_HIST PRIMARY KEY (EXECUTION_ID)
        )';
        EXECUTE IMMEDIATE 'CREATE INDEX ZIRIOAM_OWNER.IDX_ZIRIOAM_HIST_USER ON ZIRIOAM_OWNER.ZIRIOAM_EXECUTION_HISTORY(USERNAME)';
        EXECUTE IMMEDIATE 'CREATE INDEX ZIRIOAM_OWNER.IDX_ZIRIOAM_HIST_TIME ON ZIRIOAM_OWNER.ZIRIOAM_EXECUTION_HISTORY(EXECUTED_AT)';
    END IF;
END;
/

