-- 1. Table d'Installation Locale
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TABLES WHERE OWNER = 'ZIRIOAM_OWNER' AND TABLE_NAME = 'ZIRIOAM_INSTALLATION';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
        CREATE TABLE ZIRIOAM_OWNER.ZIRIOAM_INSTALLATION
        (
            INSTALLATION_ID    NUMBER GENERATED ALWAYS AS IDENTITY,
            PRODUCT_CODE       VARCHAR2(30) NOT NULL,
            PRODUCT_VERSION    VARCHAR2(30) NOT NULL,
            INSTALL_DATE       TIMESTAMP DEFAULT SYSTIMESTAMP,
            INSTALL_STATUS     VARCHAR2(20) NOT NULL,
            PDB_NAME           VARCHAR2(128) NOT NULL,
            CONSTRAINT PK_ZIRIOAM_PDB_INSTALL PRIMARY KEY (INSTALLATION_ID),
            CONSTRAINT UK_ZIRIOAM_PDB_PROD UNIQUE (PRODUCT_CODE)
        )';
    END IF;
END;
/

